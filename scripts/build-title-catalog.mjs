// Mechanical generation from a pinned historical index + the existing live-link seed.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {isCompatibleCatalogTitle} from '../shared/catalog-policy.mjs';

const baselineCommit = '85baf35a2c413ead6624458e447ae44c622f705b';
const raw = execFileSync('git', ['show', baselineCommit+':shared/random-title-pool.mjs'], {encoding:'utf8',maxBuffer:4*1024*1024});
const baseline = JSON.parse(raw.slice(raw.indexOf('Object.freeze(')+14, raw.lastIndexOf(');')));
const source = JSON.parse(readFileSync('.catalog-cache/source-index.json','utf8'));
const corrections = JSON.parse(readFileSync('server/data/catalog-corrections.json','utf8'));
const excluded = new Set([...corrections.exclude, ...Object.keys(corrections.canonicalTitles)]);
if (source.sourceRevision !== '5631a9bd17a096bab2cd02ea23adbf2327db0d91') throw Error('Unexpected source revision');
const targetCount = 100000;
const hash = title => createHash('sha256').update('namu-catalog-expansion-v1\0'+title).digest('hex');
// The September live-link seed is newer than the dump: do not interpret a historical
// rejection as a live deletion. Seed titles remain explicitly marked not live-verified.
const retained = baseline.filter(t => isCompatibleCatalogTitle(t) && !excluded.has(t));
const chosen = new Set(retained);
for (const title of Object.values(corrections.canonicalTitles)) {
  if (!isCompatibleCatalogTitle(title) || excluded.has(title)) throw Error('Invalid canonical correction');
  chosen.add(title);
}
const correctedAdditions = chosen.size - retained.length;
const compatibleHistorical = [...new Set(source.eligible.filter(t => isCompatibleCatalogTitle(t) && !excluded.has(t)))];
const candidates = compatibleHistorical
  .filter(t => !chosen.has(t)).map(title => ({title,hash:hash(title)}))
  .sort((a,b) => a.hash < b.hash ? -1 : a.hash > b.hash ? 1 : a.title < b.title ? -1 : 1);
for (const {title} of candidates) {if (chosen.size >= targetCount) break;chosen.add(title);}
if (chosen.size !== targetCount) throw Error('Insufficient eligible titles');
const titles = [...chosen].sort();
const digest = createHash('sha256').update(JSON.stringify(titles)).digest('hex');
const metadata = {
  version:'catalog-100k-2026-09-07', count:titles.length, sha256:digest,
  validation:'historical-filtered-plus-live-link-seed; not-all-live-verified',
};
const report = {
  ...metadata, sourcePage:source.sourcePage, sourceRevision:source.sourceRevision,
  snapshotDateNote:source.snapshotDateNote, sourceCounts:source.counts,
  sourceIndexPreparedAt:source.preparedAt, baselineCommit,
  baselineCount:baseline.length, retainedBaseline:retained.length,
  historicalEligibleAfterClientCompatibility:compatibleHistorical.length,
  addedFromHistoricalSnapshot:titles.length-retained.length-correctedAdditions,
  addedFromCurrentCanonicalCorrections:correctedAdditions,
  liveCorrections: {canonicalTitles:corrections.canonicalTitles,excluded:corrections.exclude},
  filter:'Historical additions: normal namespace, non-redirect, >=80 markup characters, at least one article-like link; all titles match released client normalization and exclude administration namespaces.',
  selection:'SHA-256 ranked additions across the whole eligible snapshot, not its first alphabetical rows; compatible September live-link seed titles retained except observed current corrections.',
  limits:'Historical checks do not establish current existence, live canonical title, reachability, factual quality or hint availability. Seed titles were collected from links, not exhaustively fetched.',
};
mkdirSync('docs',{recursive:true});
writeFileSync('shared/random-title-pool.mjs',
  '// Generated by scripts/build-title-catalog.mjs; data is excluded from the MIT code license.\n'
  +'// See THIRD_PARTY_NOTICES.md and docs/catalog-expansion-2026-09-07.json for provenance and limitations.\n'
  +'export const RANDOM_CATALOG = Object.freeze('+JSON.stringify(metadata)+');\n'
  +'export const RANDOM_TITLE_POOL = Object.freeze([\n'+titles.map(t=>'  '+JSON.stringify(t)).join(',\n')+'\n]);\n');
writeFileSync('docs/catalog-expansion-2026-09-07.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
